"""
__name__ == '__main__' 教學

核心問題：同一份 .py 檔，直接執行 vs 被 import，行為應該不同。
__name__ 就是用來區分這兩種情況的。
"""

# ============================================================
# Part 1：__name__ 是什麼？
# ============================================================
#
# 每個 Python 檔案都有一個內建變數 __name__
#
# 情況 A：直接執行（python demo.py）
#   → Python 把 __name__ 設為 '__main__'
#
# 情況 B：被別的檔案 import
#   → Python 把 __name__ 設為「模組名稱」（檔名去掉 .py）
#       例如 import demo → __name__ == 'demo'

print(f"目前 __name__ = {__name__!r}")


# ============================================================
# Part 2：定義可重用的函式（import 時也能用）
# ============================================================

def add(a, b):
    return a + b

def greet(name):
    return f"Hello, {name}!"


# ============================================================
# Part 3：只有「直接執行」才跑的程式碼
# ============================================================
#
# 不加這個 guard 的後果：
#   別人 import demo 只是想用 add()，
#   卻意外觸發下面的測試程式、印出東西、甚至連線 DB。

if __name__ == '__main__':
    print("\n=== 直接執行，跑測試 ===")
    print(add(1, 2))          # 3
    print(greet("Alice"))     # Hello, Alice!
